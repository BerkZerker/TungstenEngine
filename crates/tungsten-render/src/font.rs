/// Glyph bits for a character; unknown characters render as `?`.
pub fn glyph(c: char) -> u64 {
    let i = (c as u32).wrapping_sub(FIRST as u32);
    GLYPHS[if i < 95 { i as usize } else { (b'?' - FIRST) as usize }]
}
